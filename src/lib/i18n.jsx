/* The labels the server sends for documents, in the reader's language. */
const DOC_LABELS = {
  hi: { Insurance: 'बीमा', PUC: 'PUC', 'Road tax': 'रोड टैक्स', Fitness: 'फ़िटनेस',
        Permit: 'परमिट', Registration: 'पंजीकरण' },
};

const Ctx = createContext(null);

const stored = () => { try { return localStorage.getItem(KEY); } catch { return null; } };

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const s = stored();
    return s === 'hi' || s === 'en' ? s : null;
  });

  // The page's own language, so screen readers and the browser's translate
  // offer both know what they are looking at.
  useEffect(() => { document.documentElement.lang = lang === 'hi' ? 'hi' : 'en-IN'; }, [lang]);

  const setLang = useCallback((l) => {
    const v = l === 'hi' ? 'hi' : 'en';
    try { localStorage.setItem(KEY, v); } catch { /* private mode */ }
    setLangState(v);
  }, []);

  const t = useCallback((key, vars) => {
    const table = STRINGS[lang || 'en'];
    let s = table[key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
    return s;
  }, [lang]);

  const doc = useCallback((label) => (DOC_LABELS[lang]?.[label]) || label, [lang]);

  return (
    <Ctx.Provider value={{ lang: lang || 'en', chosen: Boolean(lang), setLang, t, doc }}>
      {children}
    </Ctx.Provider>
  );
}

export const useLang = () => useContext(Ctx);

/** A string with **bold** in it, as elements. */
export function Rich({ text, className = '' }) {
  const parts = String(text).split('**');
  return (
    <span className={className}>
      {parts.map((p, i) => (i % 2
        ? <b key={i} className="text-ink">{p}</b>
        : <Fragment key={i}>{p}</Fragment>))}
    </span>
  );
}
